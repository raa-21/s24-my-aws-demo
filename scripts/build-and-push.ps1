# PowerShell equivalent of build-and-push.sh for Windows VS Code.
# Requires AWS infrastructure and ECR repositories already created by Terraform.
# Use -PushGit explicitly to commit/push the image pins for ArgoCD.
[CmdletBinding()]
param(
    [ValidateSet('user-service','catalog-service','metadata-service','content-delivery-api','cache-manager','progress-tracker')]
    [string[]]$Services = @('user-service','catalog-service','metadata-service','content-delivery-api','cache-manager','progress-tracker'),
    [switch]$PushGit
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
Push-Location $root
try {
    foreach ($cmd in @('aws','terraform','docker','git')) {
        if (-not (Get-Command $cmd -ErrorAction SilentlyContinue)) { throw "Required command not found: $cmd" }
    }
    $origin = (& git remote get-url origin 2>&1 | Out-String).Trim()
    if ($LASTEXITCODE -ne 0 -or -not $origin) { throw 'Initialize Git and set origin to YOUR OWN GitHub repository before building.' }
    $tfvars = [System.IO.File]::ReadAllText((Join-Path $root 'terraform/terraform.tfvars'))
    $repoMatch = [regex]::Match($tfvars, '(?m)^gitops_repo_url\s*=\s*"([^"]+)"')
    if (-not $repoMatch.Success) { throw 'gitops_repo_url is missing from terraform.tfvars. Run prepare-personal-aws.ps1.' }
    $expectedUrl = $repoMatch.Groups[1].Value
    $originHttps = $origin -replace '^git@github.com:', 'https://github.com/'
    $normalizedOrigin = ($originHttps.TrimEnd('/') -replace '\.git$', '')
    $normalizedExpected = ($expectedUrl.TrimEnd('/') -replace '\.git$', '')
    if ($normalizedOrigin -ne $normalizedExpected) {
        throw "Git remote origin ($origin) is not the configured personal GitOps repository ($expectedUrl). Refusing to push."
    }
    $gitsha = (& git rev-parse --short HEAD 2>&1 | Out-String).Trim()
    if ($LASTEXITCODE -ne 0) { throw 'Commit and push your independent repo before building images.' }
    $region = (& terraform -chdir=terraform output -raw aws_region 2>&1 | Out-String).Trim()
    if ($LASTEXITCODE -ne 0) { throw 'Cannot read Terraform outputs. Apply the personal AWS infrastructure first.' }
    $registry = (& terraform -chdir=terraform output -raw ecr_registry 2>&1 | Out-String).Trim()
    if ($LASTEXITCODE -ne 0) { throw 'Cannot read ECR registry from Terraform state.' }
    $repoJSON = (& terraform -chdir=terraform output -json ecr_repositories 2>&1 | Out-String).Trim()
    if ($LASTEXITCODE -ne 0) { throw 'Cannot read ECR repositories from Terraform state.' }
    $repos = $repoJSON | ConvertFrom-Json
    $currentAccount = (& aws sts get-caller-identity --query Account --output text 2>&1 | Out-String).Trim()
    if ($LASTEXITCODE -ne 0 -or -not $registry.StartsWith("${currentAccount}.dkr.ecr.")) {
        throw "AWS account mismatch. Terraform ECR registry ($registry) is not owned by the currently configured AWS CLI account ($currentAccount)."
    }

    $tag = "$gitsha-$(Get-Date -Format yyyyMMddHHmmss)"
    Write-Host "Building for $registry, tag $tag"
    & aws ecr get-login-password --region $region | & docker login --username AWS --password-stdin $registry
    if ($LASTEXITCODE -ne 0) { throw 'Docker ECR login failed.' }
    foreach ($svc in $Services) {
        $repoProp = $repos.PSObject.Properties[$svc]
        if ($null -eq $repoProp) { throw "Missing ECR repo for service $svc" }
        $uri = [string]$repoProp.Value
        & docker build --platform linux/amd64 -f "services/$svc/Dockerfile" -t "${uri}:${tag}" -t "${uri}:latest" services
        if ($LASTEXITCODE -ne 0) { throw "Docker build failed for $svc" }
        & docker push "${uri}:${tag}"
        if ($LASTEXITCODE -ne 0) { throw "Docker push failed for $svc" }
        & docker push "${uri}:latest"
        if ($LASTEXITCODE -ne 0) { throw "Docker push :latest failed for $svc" }
    }

    $overlayPath = Join-Path $root 'k8s-apps/overlays/aws/kustomization.yaml'
    $oldOverlay = [System.IO.File]::ReadAllText($overlayPath)
    $oldTags = @{}
    $pattern = '- name: s24/([\w-]+)\r?\n\s+newName: [^\r\n]+\r?\n\s+newTag: "?([^"\r\n]+)"?'
    foreach ($m in [regex]::Matches($oldOverlay, $pattern)) {
        $oldTags[$m.Groups[1].Value] = $m.Groups[2].Value
    }
    $lines = New-Object 'System.Collections.Generic.List[string]'
    $lines.Add('# Generated by scripts/build-and-push.ps1. ArgoCD tracks this overlay.')
    $lines.Add('apiVersion: kustomize.config.k8s.io/v1beta1')
    $lines.Add('kind: Kustomization')
    $lines.Add('resources:')
    $lines.Add('  - ../../base')
    $lines.Add('images:')
    foreach ($svc in @('user-service','catalog-service','metadata-service','content-delivery-api','cache-manager','progress-tracker')) {
        $repoProp = $repos.PSObject.Properties[$svc]
        if ($null -eq $repoProp) { throw "Missing ECR repository $svc" }
        $useTag = if ($Services -contains $svc -or -not $oldTags.ContainsKey($svc)) { $tag } else { $oldTags[$svc] }
        $lines.Add("  - name: s24/$svc")
        $lines.Add("    newName: $($repoProp.Value)")
        $lines.Add("    newTag: `"$useTag`"")
    }
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($overlayPath, ($lines -join "`n") + "`n", $utf8)
    Write-Host "Pinned images in $overlayPath"
    if ($PushGit) {
        & git add -- k8s-apps/overlays/aws/kustomization.yaml argocd-app.yaml
        if ($LASTEXITCODE -ne 0) { throw 'git add failed' }
        & git diff --cached --quiet
        if ($LASTEXITCODE -eq 0) { Write-Host 'No Git changes to commit.' }
        else {
            & git commit -m "deploy: $($Services -join ',') @ $tag"
            if ($LASTEXITCODE -ne 0) { throw 'git commit failed' }
            & git push origin HEAD:main
            if ($LASTEXITCODE -ne 0) { throw 'git push failed; inspect permissions and branch.' }
            Write-Host 'Pushed personal GitOps changes; watch ArgoCD sync.'
        }
    } else {
        Write-Host 'No Git push performed. To sync ArgoCD, commit and push the updated overlay to your own repo.'
    }
} finally { Pop-Location }
